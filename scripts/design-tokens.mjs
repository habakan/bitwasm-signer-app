// Writes the design tokens for the web view, Android and iOS from design/tokens.json: pnpm tokens
import { readFileSync, writeFileSync } from "node:fs";

const tokens = JSON.parse(readFileSync("design/tokens.json", "utf8"));
const { light, dark } = tokens.color;
const header = "Generated by scripts/design-tokens.mjs from design/tokens.json; edit that file and run pnpm tokens";
const camel = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const names = Object.keys(light);
const missing = names.filter((n) => !(n in dark));
if (missing.length) throw new Error(`dark is missing ${missing.join(", ")}`);

const vars = (entries) => entries.map(([k, v]) => `  --${k}: ${v};`).join("\n");
writeFileSync("src/design/tokens.css", `/* ${header} */
:root {
  color-scheme: light;
${vars(Object.entries(light))}
${vars(Object.entries(tokens.size).map(([k, v]) => [k, `${v}px`]))}
${vars(Object.entries(tokens.css))}
}

/* The docs (VitePress) mark dark mode with .dark on <html> */
:root[data-theme="dark"], :root.dark {
  color-scheme: dark;
${vars(Object.entries(dark))}
  --shadow-raised: none;
}
`);

const kotlinPalette = (p) => names.map((n) => `        ${camel(n)} = 0xff${p[n].slice(1)}.toInt(),`).join("\n");
// Signer Lockdown draws its screen from the same palette
for (const [file, pkg] of [
  ["src-tauri/plugins/signer/android/src/main/java/app/bithanko/signer/DesignTokens.kt", "app.bithanko.signer"],
  ["lockdown/src/main/java/app/bithanko/lockdown/DesignTokens.kt", "app.bithanko.lockdown"],
]) writeFileSync(file, `// ${header}
package ${pkg}

internal class Palette(
${names.map((n) => `    val ${camel(n)}: Int,`).join("\n")}
)

internal object DesignTokens {
    val light = Palette(
${kotlinPalette(light)}
    )
    val dark = Palette(
${kotlinPalette(dark)}
    )
${Object.entries(tokens.size).map(([k, v]) => `    const val ${k.replace(/-/g, "_").toUpperCase()} = ${v}`).join("\n")}
}
`);

const swiftPalette = (p) => names.map((n) => `    ${camel(n)}: UIColor(rgb: 0x${p[n].slice(1)})`).join(",\n");
writeFileSync("src-tauri/plugins/signer/ios/Sources/DesignTokens.swift", `// ${header}
import UIKit

struct Palette {
${names.map((n) => `  let ${camel(n)}: UIColor`).join("\n")}
}

enum DesignTokens {
  static let light = Palette(
${swiftPalette(light)})
  static let dark = Palette(
${swiftPalette(dark)})
${Object.entries(tokens.size).map(([k, v]) => `  static let ${camel(k)}: CGFloat = ${v}`).join("\n")}
}

extension UIColor {
  convenience init(rgb: Int) {
    self.init(red: CGFloat((rgb >> 16) & 0xff) / 255, green: CGFloat((rgb >> 8) & 0xff) / 255, blue: CGFloat(rgb & 0xff) / 255, alpha: 1)
  }
}
`);
